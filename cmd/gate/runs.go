package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/lioilsources/factory-gate/internal/loop"
)

// cmdRuns prints demo/RUNS.md from the summary.json of every recording in --dir.
// The file is generated; it is never edited by hand.
func cmdRuns(args []string) int {
	fs := flag.NewFlagSet("runs", flag.ExitOnError)
	dir := fs.String("dir", "demo/recorded", "directory of recordings")
	_ = fs.Parse(args)
	paths, err := filepath.Glob(filepath.Join(*dir, "*", "summary.json"))
	if err != nil {
		return fail(err)
	}
	sort.Strings(paths)
	var runs []namedRun
	for _, p := range paths {
		data, err := os.ReadFile(p)
		if err != nil {
			return fail(err)
		}
		var r loop.Result
		if err := json.Unmarshal(data, &r); err != nil {
			return fail(fmt.Errorf("%s: %w", p, err))
		}
		runs = append(runs, namedRun{filepath.Base(filepath.Dir(p)), r})
	}
	// Recordings without a summary (an interrupted run) are listed too.
	dirs, _ := filepath.Glob(filepath.Join(*dir, "*"))
	sort.Strings(dirs)
	var incomplete []string
	for _, d := range dirs {
		if _, err := os.Stat(filepath.Join(d, "summary.json")); os.IsNotExist(err) {
			if st, err := os.Stat(d); err == nil && st.IsDir() {
				incomplete = append(incomplete, filepath.Base(d))
			}
		}
	}
	writeRuns(os.Stdout, runs, incomplete)
	return 0
}

type namedRun struct {
	Name string
	R    loop.Result
}

func writeRuns(w io.Writer, runs []namedRun, incomplete []string) {
	fmt.Fprintln(w, "# Recorded runs")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "source: recorded. Generated by `gate runs`; do not edit by hand. Capture rule: `demo/CAPTURE_RULE.md`.")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "| Run | Loop | Models | Endpoint | Context | Outcome per attempt | Tokens in / out | Model seconds |")
	fmt.Fprintln(w, "| --- | --- | --- | --- | --- | --- | --- | --- |")
	def := ""
	for _, nr := range runs {
		r := nr.R
		var outcomes, models []string
		in, out, secs := 0, 0, 0.0
		seen := map[string]bool{}
		for _, a := range r.Attempts {
			outcomes = append(outcomes, a.Outcome)
			in, out, secs = in+a.TokensIn, out+a.TokensOut, secs+a.Seconds
			if !seen[a.Model] {
				seen[a.Model] = true
				models = append(models, a.Model)
			}
		}
		shape := strings.Join(outcomes, ", ")
		if def == "" && shape == "FAIL, PASS" {
			def = nr.Name
		}
		fmt.Fprintf(w, "| %s | %s | %s | %s | %s | %s | %d / %d | %.0f |\n",
			nr.Name, r.LoopID, strings.Join(models, ", "), r.Endpoint, r.Context, shape, in, out, secs)
	}
	for _, name := range incomplete {
		fmt.Fprintf(w, "| %s | | | | | interrupted, no summary | | |\n", name)
	}
	fmt.Fprintln(w)
	switch {
	case def != "":
		fmt.Fprintf(w, "Default recording for `make demo`: **%s**, the first run with outcomes FAIL, PASS.\n", def)
	case len(runs) > 0:
		fmt.Fprintf(w, "No run has outcomes FAIL, PASS. Default recording for `make demo`: **%s**, the first run, as it is.\n", runs[0].Name)
	}
}
